function Glyph({
  char,
  color,
  off,
  dot,
  gap,
}: {
  char: string;
  color: string;
  off: string;
  dot: number;
  gap: number;
}) {
  const rows = FONT[char.toUpperCase()] ?? FONT[" "];

  return (
    <span
      className="inline-grid"
      style={{
        gridTemplateColumns: `repeat(5, ${dot}px)`,
        gap: `${gap}px`,
      }}
    >
      {rows.map((row, y) =>
        row.split("").map((cell, x) => (
          <span
            key={`${x}-${y}`}
            style={{
              width: dot,
              height: dot,
              background: cell === ON ? color : off,
            }}
          />
        ))
      )}
    </span>
  );
}

export default function DotMatrix({
  text,
  color = "var(--color-grey-90)",
  off = "var(--color-grey-10)",
  dot = 2,
  gap = 1,
}: {
  text: string;
  /** lit-dot colour */
  color?: string;
  /** unlit-dot colour, invert this on dark backgrounds */
  off?: string;
  /** size of one dot in px */
  dot?: number;
  /** space between dots in px */
  gap?: number;
}) {
  return (
    <span
      className="inline-flex items-center"
      style={{ gap: `${dot + gap}px` }}
      aria-label={text}
      role="img"
    >
      {text.split("").map((char, i) => (
        <Glyph
          key={i}
          char={char}
          color={color}
          off={off}
          dot={dot}
          gap={gap}
        />
      ))}
    </span>
  );
}
